/*==================================================================================================
 *  Mcal/fls_cfg.h —— Flash 分区与几何参数
 *
 *  【本文件回答三个问题】
 *  ① 芯片的 Flash 长什么样（Block / 扇区 / 可用边界）
 *  ② 我们把 Flash 分成几块、每块干什么
 *  ③ 哪些区域**绝对不允许**擦写
 *
 *  【S32K344 P-Flash 的物理结构（从 generate/include/C40_Ip_Cfg.h 查出）】
 *
 *      Block     扇区范围        地址范围                  大小
 *      BLOCK_0   S000 ~ S127    0x00400000 ~ 0x004FFFFF    1 MB
 *      BLOCK_1   S128 ~ S255    0x00500000 ~ 0x005FFFFF    1 MB
 *      BLOCK_2   S256 ~ S383    0x00600000 ~ 0x006FFFFF    1 MB
 *      BLOCK_3   S384 ~ S511    0x00700000 ~ 0x007FFFFF    1 MB
 *
 *      每个扇区 8 KB（0x2000）—— 这是 C40 Flash IP 的最小擦除单位
 *      BLOCK_3 的 S487（0x007CE000）之后是 HSE 固件保留区，禁止访问
 *
 *  【为什么要关心 Block，而不只是扇区】
 *  S32K344 的"边读边写"（RWW）**只在不同的 Block 之间有效**：
 *      代码跑在 BLOCK_0，擦除 BLOCK_0 的扇区  → 取指被阻塞 → 当场死机
 *      代码跑在 BLOCK_0，擦除 BLOCK_1 的扇区  → RWW 有效 → 安全
 *
 *  所以分区必须让"代码所在的 Block"和"被擦写的 Block"分开。
 *  这是本文件里 FLS_CODE_BLOCK_* 那组宏的由来。
 *================================================================================================*/
#ifndef FLS_CFG_H
#define FLS_CFG_H

/*==================================================================================================
 *                              P-Flash 几何参数
 *================================================================================================*/

/** @brief 单个扇区大小（C40 Flash IP 最小擦除单位）= 8 KB */
#define FLS_SECTOR_SIZE             (0x00002000UL)

/** @brief P-Flash 起始地址 */
#define FLS_PFLASH_START            (0x00400000UL)

/** @brief P-Flash 可用末尾（HSE 从 0x007CE000 开始保留 200 KB） */
#define FLS_PFLASH_USABLE_END       (0x007CDFFFUL)

/** @brief 单次写入最大长度（C40_Ip 硬约束：一次最多 128 字节） */
#define FLS_WRITE_MAX               (128U)

/**
 * @brief 写入对齐粒度（C40_Ip 硬约束）
 * @details 地址和长度都必须是 8 的倍数。
 *          这是 Flash 编程的"double word"（64 位）粒度。
 */
#define FLS_WRITE_ALIGN             (8U)

/** @brief Flash 擦除态的值（NOR Flash 擦完全是 0xFF） */
#define FLS_ERASED_VALUE            (0xFFU)

/**
 * @brief 是否在写入后立刻读回校验（当前：关闭）
 *
 * @details 【为什么当前关闭 —— 这是一个经过实测的工程取舍】
 *
 *  C40 Flash 的读缓冲在"编程刚结束"时不会自动更新。C40_Ip 里的处理方式是
 *  C40_Ip_InvalidPrefetchBuff()，但它被包在
 *      #if (STD_ON == C40_IP_ECC_CHECK)
 *  之下 —— 也就是 NXP 只在 "Mem ECC Enable Check" 打开时才认为它安全可用。
 *
 *  我尝试在 Fls 里手工复制那个序列（写地址 → DATA[0]=0 → 置 PGM → 清 PGM），
 *  实测结果**不稳定**：
 *      同一段校验代码，有时通过、有时读到旧数据；
 *      而且这个"假编程+放弃"如果夹在两次真编程之间，
 *      会让后一块的编程失效（驱动仍报 0x00，但 Flash 没变）。
 *
 *  结论：手工复制驱动内部函数的做法不可靠，撤掉。
 *
 *  【编程到底有没有成功，靠什么判断】
 *  靠 C40_Ip_MainInterfaceWriteStatus() 的返回值：
 *  只有当 MCRS 的 PEG 位（Program/Erase Good）= 1、PEP=0、PES=0 时
 *  才返回 SUCCESS。这是**硬件的结论**，比软件读回更可信。
 *  实测 erase 与 write 的 PEG 都正常。
 *
 *  【读回校验放在哪里】
 *  放到上层 OTA 刷写流程的最后一步：整包全部编程完成之后，
 *  再一次性读回整片区域计算 CRC，与传输过程中累加的 CRC 比对。
 *  那时已经历了大量编程操作，读缓冲自然更新；而且只需做一次，代价可接受。
 *
 *  这也是真实 Bootloader 的标准做法（CRC 校验整包，而不是逐块读回）。
 */
#ifndef FLS_VERIFY_AFTER_WRITE
    #define FLS_VERIFY_AFTER_WRITE      (STD_OFF)
#endif

/*==================================================================================================
 *                              分区规划
 *
 *   0x00400000 ┌──────────────────────────┐
 *              │  BLOCK_0  Bootloader     │  1 MB（本工程代码就在这）
 *   0x00500000 ├──────────────────────────┤
 *              │  BLOCK_1  App            │  1 MB
 *   0x00600000 ├──────────────────────────┤
 *              │  参数区（升级标志/CRC）   │  8 KB（BLOCK_2 扇区 0）
 *   0x00602000 ├──────────────────────────┤
 *              │  自检区（会被擦掉）       │  8 KB（BLOCK_2 扇区 1）
 *   0x00604000 ├──────────────────────────┤
 *              │  BLOCK_2 备用            │
 *   0x00700000 ├──────────────────────────┤
 *              │  BLOCK_3 备用            │
 *   0x007CE000 ├──────────────────────────┤
 *              │  HSE 保留 200 KB（禁碰）  │
 *   0x00800000 └──────────────────────────┘
 *================================================================================================*/

/** @brief Bootloader 分区（BLOCK_0 起始） */
#define FLS_BOOT_START              (0x00400000UL)

/** @brief Bootloader 分区大小（实际只用前 128 KB，这里按整块保护） */
#define FLS_BOOT_SIZE               (0x00100000UL)

/** @brief App 分区（BLOCK_1） */
#define FLS_APP_START               (0x00500000UL)

/** @brief App 分区大小 */
#define FLS_APP_SIZE                (0x00100000UL)

/** @brief 参数区（升级标志 / CRC / 版本号）—— BLOCK_2 扇区 0 */
#define FLS_PARAM_START             (0x00600000UL)

/** @brief 参数区大小（一个扇区） */
#define FLS_PARAM_SIZE              (FLS_SECTOR_SIZE)

/** @brief 自检区 —— BLOCK_2 扇区 1（会被反复擦写，和参数区分开） */
#define FLS_TEST_START              (0x00602000UL)

/** @brief 自检区大小（一个扇区） */
#define FLS_TEST_SIZE               (FLS_SECTOR_SIZE)

/*==================================================================================================
 *                          ★ 禁止擦写的区域（安全保护）
 *
 *  【为什么必须有这组宏】
 *  Bootloader 最严重的错误是**把自己擦掉**。一旦发生，芯片变砖
 *  （除非用调试器重新烧录）。
 *
 *  而且比"擦掉自己"更隐蔽的是：**擦同一个 Block 的其他扇区**。
 *  代码可能完整保留，但擦除期间取指被硬件阻塞 → 当场 HardFault。
 *
 *  所以 Fls_Erase / Fls_Write 会先检查请求范围是否与下面这个区间重叠，
 *  重叠就拒绝并报 Det。这属于"宁可拒绝，也不能变砖"。
 *================================================================================================*/

/** @brief 代码所在 Block 的起始地址（BLOCK_0） */
#define FLS_CODE_BLOCK_START        (0x00400000UL)

/** @brief 代码所在 Block 的结束地址（BLOCK_0 末尾） */
#define FLS_CODE_BLOCK_END          (0x004FFFFFUL)

/*==================================================================================================
 *                              超时保护
 *
 *  【为什么用循环计数，而不是 OsIf/定时器】
 *  这个项目已经因为 OSIF_COUNTER_DUMMY 吃过一次亏：
 *      OsIf_Timer_Dummy_GetElapsed() 恒返回 1（RTD/src/OsIf_Timer.c:252）
 *  于是"按微秒设定的超时"实际是"检查次数"，完全不按时间走。
 *
 *  所以 Fls 的超时一律用**纯循环计数**：
 *      擦除：约 20,000,000 次 ≈ 160 MHz 下 1.2 秒（8 KB 扇区实际只需几十毫秒）
 *      写入：同上
 *  正常绝不触发，只在硬件真卡死时兜底。
 *================================================================================================*/

/** @brief 擦除/写入等待状态的循环上限 */
#define FLS_SPIN_LIMIT              (20000000UL)

/*--------------------------------------------------------------------------------------------------
 *                        等待的"真实时间"上限（2026-10-25 新增）
 *
 * 上面 FLS_SPIN_LIMIT 是"轮询次数"上限，作为不依赖时基的兜底。
 * 但"一次轮询花多少周期"随编译优化和代码路径变化，换算成时间不确定
 * （量级 4~6 秒），既没法写进文档也没法验证。
 *
 * 所以再加这三个"毫秒"上限，和次数上限同时生效、谁先到谁生效。
 * 取值依据是实测：
 *      擦除单扇区      约 3.4 毫秒   -> 给 5 秒，余量 1400 倍
 *      写入 1 KB       约十几毫秒    -> 给 1 秒，余量 60 倍以上
 *      硬件"开工"      微秒级        -> 给 100 毫秒
 *
 * 超时后会调用 C40_Ip_Abort() 让 Flash 控制器退出忙状态，然后返回
 * C40_IP_STATUS_ERROR_TIMEOUT —— 上层（Dcm）会把它变成 NRC 0x72。
 *------------------------------------------------------------------------------------------------*/
#define FLS_HV_START_TIMEOUT_MS     (100U)
#define FLS_ERASE_TIMEOUT_MS        (5000U)
#define FLS_WRITE_TIMEOUT_MS        (1000U)

/** @brief 等待状态时每次轮询的粒度提示（仅用于注释说明，不参与判断） */
#define FLS_POLL_GRANULARITY        (1000UL)

#endif /* FLS_CFG_H */
