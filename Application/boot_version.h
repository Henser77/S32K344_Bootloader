/*==================================================================================================
 *  Application/boot_version.h —— 固件版本标识
 *
 *  【为什么需要这个文件】
 *  排查问题时最难的一类困惑是"板子里到底跑的是哪个版本"。
 *  横幅里只有构建时间（`__DATE__ __TIME__`），但：
 *      - 改了代码没重新编译 → 时间不变，看不出
 *      - 时间差几小时 → 人脑算不清对应哪个提交
 *
 *  2026-10-23 就真的踩过一次：板子跑的是 20:05 编译的固件，
 *  而 21:24 才补上"刷写成功后记账"那段代码，
 *  结果"刷写成功但永远不跳 App"，查了半天才发现是固件旧了。
 *
 *  所以这里放一个**人工维护**的版本号 + 功能清单，横幅里打出来。
 *  **任何会改变外部行为的改动，都必须在这里加一条。**
 *================================================================================================*/
#ifndef BOOT_VERSION_H
#define BOOT_VERSION_H

/* 构建模式与全部派生开关（开发版/发布版的唯一派生点） */
#include "build_cfg.h"

/**
 * @brief 固件版本号
 *
 * @details 命名约定（只列"外部可观察行为变了"的版本）：
 *
 *      1.0   分层架构（EcuM/CanIf/PduR）+ 上电 7 步校验 + 跳转
 *      1.1   升级标志接进流程：擦除前先置无效、CRC 通过后才置有效
 *      1.2   新增 CAN 收发计数打印（用来诊断"发了不回"）
 *      1.3   0x11 01 补上真正的复位动作（原来只置标志、没人执行）
 *      1.4   新增 1.5 秒启动窗口（App 有效时也能进刷写）
 *      1.5   修 Dcm 响应缓冲被静默覆盖；加发布总开关
 *      1.6   S32K344 的 AIRCR.SYSRESETREQ 不产生复位
 *            -> 改成"请求后等 50 ms，没复位就清标志继续跑"，不再死等
 *      1.7   复位失败时改为"重新校验 App -> 直接跳转"
 *      1.8   Flash 擦写加"真实时间"上限（超时 Abort）；
 *            修 Dcm_Init 重复清零 CYCCNT 会打乱 CanTp 时基的隐患；
 *            新增调试例程 0xFF02
 *      1.9   复位改用 MC_ME（NXP 官方 Mcu_PerformReset 走的就是这条）
 *      1.10  日志瘦身：帧打印默认关，0x36 改成每 16 块一行
 *            （原来刷一次打 5100 行 / 350 KB，串口软件直接崩）
 *      1.11  ★修 CanTp 时间基准的并发竞态
 *            （读-改-写被 CAN 中断打断 -> UsCounter 回退 -> N_Cr 超时下溢误判）
 *            这一版同时把刷写从 55 秒降到 12 秒（不再靠 2 ms 帧间隔绕 bug）
 *      1.12  复位改回 MC_ME；上位机新增 --reset-only 单项测试
 *      1.13  ★修正 MC_ME 的钥匙顺序：钥匙是"启动硬件动作"的那一下，
 *            必须写在 MODE_CONF/MODE_UPD **之后**  -> 复位终于成功
 *      1.14  开发版/发布版统一到 Library/build_cfg.h：
 *            改 BOOT_BUILD_MODE 一行，日志/DET/追踪/后门/宽松超时/窗口 8 项一起切换
 *            （发布版实测省 5.6 KB，ELF 里中文字符串 0 条）
 *      1.15  发布版启动窗口 0 -> 1000 ms
 *            （设 0 会导致"App 有效时再也进不去 Bootloader"，实测踩到）
 *      1.16  新增 BootRequest"门铃"：例程 0xFF03 置位 / 0xFF04 清除，
 *            Bootloader 上电消费一次 -> 不必依赖启动窗口
 */
#define BOOT_FW_VERSION             "1.16"

/**
 * @brief 功能清单（横幅里打印，用来一眼确认"这版有没有某个能力"）
 *
 * @note 最多约 60 个汉字，太长会占满一行。
 */
#define BOOT_FW_FEATURES            "分层+7步校验+AppValid+MC_ME复位+1s窗口+门铃0xFF03+CAN计数"

/**
 * @brief 外部可观察的行为变了就要加一
 *
 * @details 判断标准很简单：
 *          "如果这一条不同，诊断仪/上位机的操作会不会不一样？"
 *          会 → 必须改版本号和上面的功能清单。
 */
#define BOOT_FW_VERSION_NOTE        "刷写成功后由 31 01 FF01 写 AppValid=1"

/*==================================================================================================
 *  开发版 / 发布版
 *
 *  全部开关（日志级别、DET、调试追踪、0xFF02 后门、宽松超时、启动窗口）
 *  已经统一到 Library/build_cfg.h，由 BOOT_BUILD_MODE 一处派生。
 *
 *      改源码       Library/build_cfg.h 里改 BOOT_BUILD_MODE
 *      不改源码     S32DS 的 Release_FLASH 配置里加 -DBOOT_BUILD_MODE=1
 *
 *  详见 Library/build_cfg.h 的文件头，以及 README 第七节。
 *================================================================================================*/

#endif /* BOOT_VERSION_H */
