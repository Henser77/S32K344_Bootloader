/*==================================================================================================
 *  src/boot_trace.h —— 调试上报（本工程专用，不属于 AUTOSAR 的任何一层）
 *
 *  【为什么单独成模块】
 *  这些输出对调试极其有用，但**正式产品必须整体关掉**：
 *      - "打印应回密钥"那行等于公开安全访问的解锁方法
 *      - 逐帧打印会拖慢主循环
 *
 *  以前它们散在 main.c 里（占了近 100 行），既关不掉也看不清主流程。
 *  现在集中到这里，用一个开关整体控制：
 *
 *      BOOT_TRACE_ENABLE = STD_OFF  →  所有输出和轮询全部消失
 *
 *  【它和 CanIf / PduR 的关系】
 *  通过 CanIf 的"接收观察回调"拿到原始帧（不抢 CanIf 的协议处理），
 *  通过 PduR 的请求通知拿到"这条 UDS 请求被谁处理了"。
 *  两条路都是被动接收，不影响协议栈。
 *================================================================================================*/
#ifndef BOOT_TRACE_H
#define BOOT_TRACE_H

#include "Std_Types.h"
#include "boot_version.h"   /* BOOT_BUILD_MODE / 全部开关 */
#include "ComStack_Types.h"

/*==================================================================================================
 *                                    开关（正式产品改成 STD_OFF）
 *================================================================================================*/
/* BOOT_TRACE_ENABLE / BOOT_TRACE_SHOW_KEY / BOOT_TRACE_SHOW_FRAMES
 * 已经统一在 Library/build_cfg.h 里由 BOOT_BUILD_MODE 派生。
 *
 * 发布版：三个全 STD_OFF -> 本文件 429 行以下的 #else 分支把整个模块
 *         变成一堆空函数，Flash 里不占空间。
 * 开发版：ENABLE=ON，SHOW_FRAMES=OFF（每帧打印会把串口打爆）。 */

/**
 * @brief 是否打印"应回密钥"和可直接照抄的密钥帧
 *
 * @details ⚠️ **正式发布必须设成 STD_OFF**
 *
 *          这一项打开时，串口会输出：
 *              种子=0xXXXXXXXX，应回密钥=0xXXXXXXXX
 *              >> 请发送这一帧: 06 27 02 XX XX XX XX CC
 *          等于把安全访问的解锁方法公开写在日志里。
 *
 *          之所以单独一个开关（而不是跟 BOOT_TRACE_ENABLE 合并）：
 *              手工测试阶段需要它（诊断仪不会自己算密钥）
 *              其它调试输出（帧、UDS 摘要、超时）发布时也可能有用
 *          两者分开，发布时只关这一个，不必牺牲全部调试能力。
 */
/* 同样已由 build_cfg.h 派生：开发版 ON，发布版 OFF。 */

/**
 * @brief 是否打印"每一帧原始数据"（默认关）
 *
 * @details 【为什么默认关 —— 刷写时会把串口打爆】
 *
 *  刷一次 31888 字节的固件，ECU 要收 4878 帧、发 269 帧。
 *  Trace_PrintFrame 每帧还要"逐字节"调 Uart_Printf（一帧约 9 次），
 *  也就是约 4.4 万次阻塞式串口调用、约 350 KB 输出。
 *  115200 下光传输就要 30 秒，而整个刷写才 55 秒。
 *
 *  关键危害不是"看着烦"：Uart_Printf 是**阻塞轮询**的，
 *  这 30 秒会直接挤占 CanTp 处理连续帧的时机，
 *  表现为丢帧 / 传输中止 / 上位机"等响应超时"。
 *
 *  所以刷写时关掉，只保留 UDS 请求摘要 + 错误 + 统计。
 *  要手工追单条命令的帧细节时再打开。
 */
/* 同样已由 build_cfg.h 派生：两个版本都是 STD_OFF。 */

/**
 * @brief 传输数据（0x36）阶段每多少块打印一次进度
 *
 * @details 125 块如果每块都打，光这一阶段就 375 行。
 *          改成每 16 块一行，125 块一共 8 行。
 *          第 1 块总是会打（确认传输真的开始了）。
 */
#ifndef BOOT_TRACE_XFER_PROGRESS_EVERY
    #define BOOT_TRACE_XFER_PROGRESS_EVERY   (16U)
#endif

/*==================================================================================================
 *                                        API
 *================================================================================================*/

/**
 * @brief 初始化调试上报
 * @details 注册 CanIf 的接收观察回调（把原始帧拷进环形缓冲）。
 * @pre 必须在 CanIf_Init 之后调用
 */
void BootTrace_Init(void);

/**
 * @brief 主循环调用：打印那些"轮询型"的事件
 * @details S3 会话超时、CanTp 传输中止、接收缓冲溢出、原始 CAN 帧。
 */
void BootTrace_MainFunction(void);

/**
 * @brief PduR 处理完一条 UDS 请求后调用
 * @param[in] Req     请求的完整字节
 * @param[in] ReqLen  长度
 * @note 专门打印"给人看"的东西：请求摘要、当前会话/安全状态、
 *       以及（仅调试用）期望密钥和可直接照抄的密钥帧。
 */
void BootTrace_OnUdsRequest(const uint8* Req, uint32 ReqLen);

#endif /* BOOT_TRACE_H */
