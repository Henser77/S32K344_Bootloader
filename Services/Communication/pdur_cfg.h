/*==================================================================================================
 *  Services/Communication/pdur_cfg.h —— PduR 路由表配置
 *
 *  【PduR 唯一要配的东西就是"路由表"】
 *  本工程只有一条路由链：
 *
 *      接收：CanIf 接收 PDU 0  →  CanTp 接收 PDU 0
 *      发送：Dcm  发送 PDU 0   →  CanTp 发送 PDU 0  →  CanIf 发送 PDU 0
 *
 *  看起来"绕了三层"，但每一层都不需要知道别人用的是什么编号，
 *  换一个上层模块（比如把 Dcm 换成别的诊断实现）只改这个文件。
 *================================================================================================*/
#ifndef PDUR_CFG_H
#define PDUR_CFG_H

/*==================================================================================================
 *                                    接收路由（下层 → 上层）
 *================================================================================================*/

/** @brief CanIf 接收 PDU 编号 → CanTp 接收 PDU 编号（本工程都是 0） */
#define PDUR_CANIF_RX_TO_CANTP      (0U)

/*==================================================================================================
 *                                    发送路由（上层 → 下层）
 *================================================================================================*/

/** @brief Dcm 发送 PDU 编号（PduR 内部编号） */
#define PDUR_DCM_TX_PDU_ID          (0U)

/** @brief Dcm 的响应 → CanTp 的发送 PDU 编号 */
#define PDUR_DCM_TX_TO_CANTP        (0U)

/** @brief CanTp 的 N-PDU 发送 → CanIf 的发送 PDU 编号 */
#define PDUR_CANTP_TX_TO_CANIF      (0U)

/** @brief 发送路由表项数 */
#define PDUR_DCM_TX_PDU_COUNT       (1U)

#endif /* PDUR_CFG_H */
